"""Builds self-hosted, subset fonts for oiacafe-v2/.
Usage: python3 tools/oia-fonts.py <dir with extracted @fontsource packages: noto-serif-tc/, noto-sans-tc/, cormorant-garamond/>
Re-run after changing any text in oiacafe-v2 (otherwise new characters fall back to system fonts)."""
import pathlib, re, sys
from fontTools import subset
from fontTools.ttLib import TTFont

root = pathlib.Path(__file__).resolve().parent.parent / 'oiacafe-v2'
src = pathlib.Path(sys.argv[1])
FACES = [('noto-serif-tc', ['500.css', '600.css']), ('noto-sans-tc', ['400.css', '500.css']),
         ('cormorant-garamond', ['400.css', '400-italic.css', '500-italic.css'])]
used = set(chr(c) for c in range(0x20, 0x7f))
for p in list(root.glob('*.html')) + list((root / 'assets').glob('*.js')):
    used |= set(p.read_text(encoding='utf-8'))
cps = {ord(c) for c in used}

def covers(rng):
    for part in rng.split(','):
        a, _, b = part.strip()[2:].partition('-')
        a = int(a, 16); b = int(b, 16) if b else a
        if any(a <= c <= b for c in cps): return True
    return False

out = root / 'assets' / 'fonts'; out.mkdir(parents=True, exist_ok=True)
for f in out.glob('*.woff2'): f.unlink()
css = ['/* generated by tools/oia-fonts.py — do not edit */']
total = 0
for pkg, files in FACES:
    base = src / pkg / 'package'
    for cssf in files:
        for block in re.findall(r'@font-face\s*{[^}]+}', (base / cssf).read_text()):
            rng = re.search(r'unicode-range:\s*([^;]+);', block)
            if rng and not covers(rng.group(1)): continue
            url = re.search(r'url\(\./files/([^)]+\.woff2)\)', block).group(1)
            font = TTFont(base / 'files' / url)
            opts = subset.Options(); opts.flavor = 'woff2'; opts.layout_features = ['*']
            s = subset.Subsetter(opts); s.populate(text=''.join(used)); s.subset(font)
            if not font['cmap'].getBestCmap(): continue
            font.flavor = 'woff2'; font.save(out / url); total += (out / url).stat().st_size
            fam = re.search(r"font-family:\s*'([^']+)'", block).group(1)
            style = re.search(r'font-style:\s*(\w+)', block).group(1)
            weight = re.search(r'font-weight:\s*(\d+)', block).group(1)
            css.append(f"@font-face{{font-family:'{fam}';font-style:{style};font-weight:{weight};font-display:swap;src:url(fonts/{url}) format('woff2');"
                       + (f"unicode-range:{rng.group(1)};" if rng else '') + '}')
(root / 'assets' / 'fonts.css').write_text('\n'.join(css) + '\n', encoding='utf-8')
print(f'{len(css)-1} faces, {total//1024} KB')
